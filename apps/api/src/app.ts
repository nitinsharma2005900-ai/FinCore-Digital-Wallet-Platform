import express from 'express';
import cors from 'cors';
import helmet from 'helmet';
import cookieParser from 'cookie-parser';
import {rateLimit} from 'express-rate-limit';
import {config} from './config';
import {db,errors,requestId,send} from './core';
import {auth,authenticate} from './auth';
import {customer} from './customer';
import {payments,webhook} from './payments';
import {statements} from './statements';
import {staff} from './staff';
export const app=express();
app.disable('x-powered-by');app.use(requestId,helmet(),cors({origin:config.WEB_ORIGIN,credentials:true}),cookieParser());
app.get('/health',(_req,res)=>res.json({status:'ok',simulation:true}));
app.get('/ready',async(_req,res)=>{await db.$queryRaw`SELECT 1`;send(res,{database:'ok'});});
app.post('/api/v1/webhooks/payments',express.raw({type:'application/json',limit:'100kb'}),webhook);
app.use(express.json({limit:'100kb'}),rateLimit({windowMs:60000,limit:300}));
app.use('/api/v1/auth',auth);
app.use('/api/v1',authenticate,customer);
app.use('/api/v1',staff);
app.use('/api/v1/payment-intents',payments);
app.use('/api/v1/statements',statements);
app.use((_req,res)=>res.status(404).json({error:{code:'NOT_FOUND',message:'Endpoint not found'}}));app.use(errors);
